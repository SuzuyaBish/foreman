#!/usr/bin/env bash
# crew-pi-ext.sh - write the extension a crew member runs with.
# Usage: crew-pi-ext.sh <id> <busy-gen>
#
# The file lives outside the worktree (in this home's state directory) because
# pi's folder-trust gate fires on any extension loaded from inside a project,
# and because a project-local file would pollute the captain's repository.
#
# It provides two things:
#   * semantic turn state, so the foreman can tell "mid-turn" from "idle at its
#     prompt" rather than guessing from a rendered screen;
#   * the Lavish review loop, whose poll must be a tracked background job that
#     resumes this same session — which is exactly a child of this process.
set -eu

. "$(cd "$(dirname "$0")" && pwd)/foreman-lib.sh"

ID=${1:-}
GEN=${2:-}
DIR=$(foreman_require_task "$ID") || exit 1
[ -n "$GEN" ] || foreman_die "crew-pi-ext.sh needs the busy generation token"

TARGET="$DIR/pi-ext.ts"
TMP="$TARGET.tmp.$$"

cat >"$TMP" <<'TSEOF'
// Generated by foreman for crew task __ID__. Rewritten at every launch; do not
// edit by hand. Provides semantic turn state and the Lavish review loop.
import { execFile, spawn } from "node:child_process";

export default function (pi: any) {
  const GEN = "__GEN__";
  const HOME = "__HOME__";
  const ID = "__ID__";
  const BUSY = "__BUSY_EVENT__";

  const report = (state: string, event: string) =>
    new Promise<void>((resolve) => {
      execFile(
        BUSY,
        ["apply", HOME, ID, state, "--gen", GEN, "--source", "crew-ext", "--event", event],
        () => resolve(),
      );
    });

  pi.on("agent_start", () => report("busy", "agent-start"));
  pi.on("agent_settled", (_event: any, ctx: any) => {
    // Settled means pi will not continue automatically: retries, compaction,
    // tool loops and queued continuations all keep the run un-settled.
    if (ctx && typeof ctx.isIdle === "function" && !ctx.isIdle()) return;
    return report("idle", "agent-settled");
  });

  let poll: any = null;

  pi.registerTool({
    name: "lavish_open",
    label: "Open Lavish board",
    description:
      "Open or resume a Lavish review board for an HTML artifact, so the captain can " +
      "annotate it in the browser and send structured feedback back. Use it whenever " +
      "your deliverable is visual, or when a decision is easier to review visually " +
      "than in prose.",
    parameters: {
      type: "object",
      properties: {
        file: { type: "string", description: "Path to the HTML artifact" },
      },
      required: ["file"],
    },
    async execute(_toolCallId: string, params: any) {
      return await new Promise((resolve: any) => {
        execFile(
          "lavish-axi",
          [params.file],
          { cwd: process.cwd(), maxBuffer: 8 * 1024 * 1024 },
          (err: any, stdout: string, stderr: string) => {
            const text = `${stdout || ""}${stderr || ""}`.trim();
            resolve({
              content: [{ type: "text", text: text || String(err) }],
              details: undefined,
            });
          },
        );
      });
    },
  });

  pi.registerTool({
    name: "lavish_poll",
    label: "Wait for board feedback",
    description:
      "Wait for the captain's feedback on a Lavish board. This is a tracked wait: it " +
      "resumes you with whatever the captain sent. Call it once after opening a board " +
      "and leave it running — never kill it, and never try to poll with a shell.",
    parameters: {
      type: "object",
      properties: {
        file: { type: "string", description: "Path to the HTML artifact" },
      },
      required: ["file"],
    },
    async execute(_toolCallId: string, params: any) {
      if (poll) {
        return {
          content: [{ type: "text", text: `already polling — feedback is on its way` }],
          details: undefined,
        };
      }
      return await new Promise((resolve: any) => {
        const child = spawn("lavish-axi", ["poll", params.file], {
          cwd: process.cwd(),
          stdio: ["ignore", "pipe", "pipe"],
        });
        poll = child;
        let out = "";
        child.stdout?.on("data", (d: Buffer) => {
          if (out.length < 65536) out += d.toString();
        });
        child.stderr?.on("data", (d: Buffer) => {
          if (out.length < 65536) out += d.toString();
        });
        child.on("exit", () => {
          poll = null;
          const text = out.trim().slice(0, 60000);
          if (text) {
            try {
              pi.sendUserMessage(`Lavish board feedback:\n${text}`, { deliverAs: "followUp" });
            } catch {
              /* nothing to resume */
            }
          }
          resolve({
            content: [{ type: "text", text: text ? "board feedback delivered" : "board closed with nothing" }],
            details: undefined,
          });
        });
      });
    },
  });

  pi.on("session_shutdown", () => {
    try {
      poll?.kill("SIGTERM");
    } catch {
      /* already gone */
    }
    poll = null;
    return report("unknown", "session-shutdown");
  });
}
TSEOF

sed -e "s|__ID__|$ID|g" \
  -e "s|__GEN__|$GEN|g" \
  -e "s|__HOME__|$FOREMAN_HOME|g" \
  -e "s|__BUSY_EVENT__|$FOREMAN_ROOT/bin/crew-busy-event.sh|g" \
  "$TMP" >"$TARGET"
rm -f "$TMP"
printf '%s\n' "$TARGET"
