#!/usr/bin/env bash
# crew-pi-ext.sh - write the extension a crew member runs with.
# Usage: crew-pi-ext.sh <id> <busy-gen>
#
# The file lives outside the worktree (in this home's state directory) because
# pi's folder-trust gate fires on any extension loaded from inside a project,
# and because a project-local file would pollute the captain's repository.
#
# It provides three things:
#   * semantic turn state, so the foreman can tell "mid-turn" from "idle at its
#     prompt" rather than guessing from a rendered screen;
#   * the `crew_report` tool, so a crew member reports through a typed tool
#     instead of a hand-quoted bash command;
#   * the Lavish review loop, whose poll must be a tracked background job that
#     resumes this same session — which is exactly a child of this process.
set -eu

. "$(cd "$(dirname "$0")" && pwd)/foreman-lib.sh"

ID=${1:-}
GEN=${2:-}
DIR=$(foreman_require_task "$ID") || exit 1
[ -n "$GEN" ] || foreman_die "crew-pi-ext.sh needs the busy generation token"

TARGET="$DIR/pi-ext.ts"
TMP="$TARGET.tmp.$$"

cat >"$TMP" <<'TSEOF'
// Generated by foreman for crew task __ID__. Rewritten at every launch; do not
// edit by hand. Provides semantic turn state, the crew_report tool, and the
// Lavish review loop.
import { execFile, spawn } from "node:child_process";

export default function (pi: any) {
  const GEN = "__GEN__";
  const HOME = "__HOME__";
  const ID = "__ID__";
  const BUSY = "__BUSY_EVENT__";
  const REPORT = "__REPORT__";

  // `lavish-axi` results end with a full DOM serialization of the artifact. It
  // is the largest part of the response and it is not the feedback, so trim it
  // and cap the rest, the same way every other result reaching a model is capped.
  const boundLavish = (raw: string) => {
    const trimmed = raw.trim().replace(/^dom_snapshot: .*$/m, "dom_snapshot: …[trimmed]");
    return trimmed.length > 4000 ? `${trimmed.slice(0, 4000)}\n…[capped at 4000 chars]` : trimmed;
  };

  const report = (state: string, event: string) =>
    new Promise<void>((resolve) => {
      execFile(
        BUSY,
        ["apply", HOME, ID, state, "--gen", GEN, "--source", "crew-ext", "--event", event],
        () => resolve(),
      );
    });

  pi.on("agent_start", () => report("busy", "agent-start"));
  pi.on("agent_settled", (_event: any, ctx: any) => {
    // Settled means pi will not continue automatically: retries, compaction,
    // tool loops and queued continuations all keep the run un-settled.
    if (ctx && typeof ctx.isIdle === "function" && !ctx.isIdle()) return;
    return report("idle", "agent-settled");
  });

  // --- reporting -----------------------------------------------------------
  // The crew's only way to tell the foreman anything. The bash script stays the
  // single owner of validation; the tool just carries the call, with the home
  // passed explicitly because a crew's shell does not inherit FOREMAN_HOME.
  pi.registerTool({
    name: "crew_report",
    label: "Report to the foreman",
    description:
      "Record what you just did, so the foreman and the captain can see it. This " +
      "is how you report; do not shell out to crew-report.sh.\n\n" +
      "  working            a phase started; clears a bare blocked\n" +
      "  progress           a milestone worth recording (never changes the state)\n" +
      "  needs-decision     a question the captain must answer: note is the question, key names it\n" +
      "  blocked            an obstacle, no decision owed\n" +
      "  review             the change is ready; pass the pull request as pr\n" +
      "  done               finished (a report task, or work already merged)\n" +
      "  failed             cannot be completed\n" +
      "\nA done status with no report file is a failed task.",
    parameters: {
      type: "object",
      properties: {
        verb: {
          type: "string",
          enum: ["working", "progress", "needs-decision", "blocked", "review", "done", "failed", "stopped"],
          description: "What to record",
        },
        note: { type: "string", description: "One line: the summary, reason, or question" },
        key: {
          type: "string",
          description: "Required with needs-decision: a short bare token naming the question",
        },
        pr: { type: "string", description: "Only with review: the pull request url or number" },
      },
      required: ["verb"],
    },
    async execute(_toolCallId: string, params: any) {
      const args: string[] = [ID, String(params.verb)];
      if (params.note) args.push(String(params.note));
      if (params.key) args.push("--key", String(params.key));
      if (params.pr) args.push("--pr", String(params.pr));
      return await new Promise((resolve: any) => {
        execFile(
          REPORT,
          args,
          { env: { ...process.env, FOREMAN_HOME: HOME }, maxBuffer: 1024 * 1024 },
          (err: any, stdout: string, stderr: string) => {
            const text = `${stdout || ""}${stderr || ""}`.trim();
            resolve({
              content: [{ type: "text", text: text || (err ? String(err) : "reported") }],
              details: undefined,
            });
          },
        );
      });
    },
  });

  let poll: any = null;

  pi.registerTool({
    name: "lavish_open",
    label: "Open Lavish board",
    description:
      "Open or resume a Lavish review board for an HTML artifact, so the captain can " +
      "annotate it in the browser and send structured feedback back. Use it whenever " +
      "your deliverable is visual, or when a decision is easier to review visually " +
      "than in prose.",
    parameters: {
      type: "object",
      properties: {
        file: { type: "string", description: "Path to the HTML artifact" },
      },
      required: ["file"],
    },
    async execute(_toolCallId: string, params: any) {
      return await new Promise((resolve: any) => {
        execFile(
          "lavish-axi",
          [params.file],
          { cwd: process.cwd(), maxBuffer: 8 * 1024 * 1024 },
          (err: any, stdout: string, stderr: string) => {
            const text = boundLavish(`${stdout || ""}${stderr || ""}`);
            resolve({
              content: [{ type: "text", text: text || String(err) }],
              details: undefined,
            });
          },
        );
      });
    },
  });

  pi.registerTool({
    name: "lavish_poll",
    label: "Wait for board feedback",
    description:
      "Wait for the captain's feedback on a Lavish board. This is a tracked wait: it " +
      "resumes you with whatever the captain sent. Call it once after opening a board " +
      "and leave it running — never kill it, and never try to poll with a shell.",
    parameters: {
      type: "object",
      properties: {
        file: { type: "string", description: "Path to the HTML artifact" },
      },
      required: ["file"],
    },
    async execute(_toolCallId: string, params: any) {
      if (poll) {
        return {
          content: [{ type: "text", text: `already polling — feedback is on its way` }],
          details: undefined,
        };
      }
      return await new Promise((resolve: any) => {
        const child = spawn("lavish-axi", ["poll", params.file], {
          cwd: process.cwd(),
          stdio: ["ignore", "pipe", "pipe"],
        });
        poll = child;
        let out = "";
        child.stdout?.on("data", (d: Buffer) => {
          if (out.length < 65536) out += d.toString();
        });
        child.stderr?.on("data", (d: Buffer) => {
          if (out.length < 65536) out += d.toString();
        });
        child.on("exit", () => {
          poll = null;
          const text = boundLavish(out);
          if (text) {
            try {
              pi.sendUserMessage(`Lavish board feedback:\n${text}`, { deliverAs: "followUp" });
            } catch {
              /* nothing to resume */
            }
          }
          resolve({
            content: [{ type: "text", text: text ? "board feedback delivered" : "board closed with nothing" }],
            details: undefined,
          });
        });
      });
    },
  });

  pi.on("session_shutdown", () => {
    try {
      poll?.kill("SIGTERM");
    } catch {
      /* already gone */
    }
    poll = null;
    return report("unknown", "session-shutdown");
  });
}
TSEOF

sed -e "s|__ID__|$ID|g" \
  -e "s|__GEN__|$GEN|g" \
  -e "s|__HOME__|$FOREMAN_HOME|g" \
  -e "s|__BUSY_EVENT__|$FOREMAN_ROOT/bin/crew-busy-event.sh|g" \
  -e "s|__REPORT__|$FOREMAN_ROOT/bin/crew-report.sh|g" \
  "$TMP" >"$TARGET"
rm -f "$TMP"
printf '%s\n' "$TARGET"
