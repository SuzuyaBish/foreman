#!/usr/bin/env bash
# house-demo.sh - a reproducible scratch cast for exercising house end to end.
#
# Usage: house-demo.sh seed [--bind <crew-id>]
#        house-demo.sh clear
#        house-demo.sh --help
#
# `seed` installs a small fictional cast of four areas into the normal chart so
# the whole loop - rounds, prescribe, send - can be exercised with no real
# areas to hand. Every chart it writes carries the `demo fixture` marker in its
# log. `clear` removes exactly those marked charts and their outbox
# prescriptions, and never a real area: a chart without the marker is left
# alone and named. This is a scratch fixture, not the captain's work.
set -eu

. "$(cd "$(dirname "$0")" && pwd)/house-lib.sh"

# Written into every seeded chart's log. A chart is the demo's own if and only
# if its log carries this exact text; that is the whole safety rule.
HOUSE_DEMO_MARKER='demo fixture'

# The cast, one area per kind. The names are the invented ones the docs and the
# captain's hand-made cast already use.
HOUSE_DEMO_SLUGS="atlas harbour lighthouse palette"

usage() {
  cat <<'EOF'
usage: house-demo.sh seed [--bind <crew-id>]
       house-demo.sh clear

seed     install a scratch cast of four areas (a repo, a chat, a deck and a
         stale craft) into the chart, each carrying the "demo fixture" marker.
         --bind <crew-id> binds the chat area to a live crew task so
         house-send's dry run resolves; the default binds a placeholder that
         does not, which exercises house-send's refusal-and-point-at---copy
         path.
clear    remove exactly the demo areas and their outbox prescriptions. A chart
         without the "demo fixture" marker is left alone and reported by name.
EOF
}

# True when a chart's log carries the marker. Only the log counts: a real area
# could mention the phrase in its status and must not be mistaken for ours.
house_demo_marked() { # <path>
  sed -n '/^## Log/,$p' "$1" 2>/dev/null | grep -qF "$HOUSE_DEMO_MARKER"
}

# A date <days> ago, GNU or BSD date, so a seeded chart is always stale.
house_demo_backdate() { # <days-ago>
  date -u -v-"$1"d +%Y-%m-%d 2>/dev/null ||
    date -u -d "$1 days ago" +%Y-%m-%d
}

house_demo_write() { # <slug> <title> <kind> <where> <bind> <updated> <status> <next>
  local slug=$1 title=$2 kind=$3 where=$4 bind=$5 updated=$6 status=$7 next=$8
  local path opened
  path=$(house_area_path "$slug")
  opened=$(house_today)
  {
    printf '# house area: %s\n\n' "$slug"
    printf 'slug: %s\n' "$slug"
    printf 'title: %s\n' "$title"
    printf 'kind: %s\n' "$kind"
    printf 'where: %s\n' "$where"
    printf 'bind: %s\n' "$bind"
    printf 'opened: %s\n' "$opened"
    printf 'updated: %s\n' "$updated"
    printf 'status: %s\n' "$status"
    printf 'next: %s\n' "$next"
    printf '\n## Log\n\n'
    printf -- '- %s - %s; generated by house-demo.sh; safe to remove\n' \
      "$opened" "$HOUSE_DEMO_MARKER"
  } >"$path"
}

seed() {
  local bind=demo-crew
  while [ $# -gt 0 ]; do
    case "$1" in
    --bind)
      [ $# -ge 2 ] || house_die "--bind requires a value"
      bind=$2
      shift 2
      ;;
    *) house_die "unknown seed option: $1 (try --help)" ;;
    esac
  done

  # Refuse before writing anything. A chart without the marker is a real area,
  # and seed must never clobber one; report every collision so the choice is
  # the captain's, not ours.
  local slug path refused=
  for slug in $HOUSE_DEMO_SLUGS; do
    path=$(house_area_path "$slug")
    [ -f "$path" ] || continue
    house_demo_marked "$path" || refused="$refused $slug"
  done
  if [ -n "$refused" ]; then
    house_die "refusing to overwrite non-demo area(s):$refused (they lack the '$HOUSE_DEMO_MARKER' marker)"
  fi

  local stale
  stale=$(house_demo_backdate 30)
  mkdir -p "$HOUSE_AREAS"

  local seeded=0 kept=0
  for slug in $HOUSE_DEMO_SLUGS; do
    path=$(house_area_path "$slug")
    if [ -f "$path" ]; then
      # It already exists and carries the marker; re-seeding is a no-op.
      printf 'house: kept %s (already a demo fixture)\n' "$slug"
      kept=$((kept + 1))
      continue
    fi
    case "$slug" in
    atlas)
      # The chart records the literal path, exactly as the README's sample does.
      # shellcheck disable=SC2088
      house_demo_write atlas "Atlas" repo "~/code/atlas" "" "$(house_today)" \
        "parser merged; flags half done" "add --dry-run to the CLI"
      ;;
    harbour)
      house_demo_write harbour "Harbour" chat "chat: harbour" "$bind" "$(house_today)" \
        "kick-off done, scope agreed" "draft the milestone plan"
      ;;
    lighthouse)
      house_demo_write lighthouse "Lighthouse deck" deck "deck: lighthouse.key" "" "$(house_today)" \
        "out for review" "tighten the ask to one line per slide"
      ;;
    palette)
      # Deliberately stale and with no next, so rounds marks both.
      house_demo_write palette "Palette" craft "craft: design system" "" "$stale" \
        "tokens split across two files" ""
      ;;
    esac
    printf 'house: seeded %s (%s)\n' "$slug" "$(house_field "$path" kind)"
    seeded=$((seeded + 1))
  done

  if [ "$seeded" -eq 0 ]; then
    printf 'house: demo areas already present (%s); nothing to do\n' "$kept"
  fi
}

clear() {
  local slug path f removed=0 demo_slugs=" "
  for slug in $HOUSE_DEMO_SLUGS; do
    path=$(house_area_path "$slug")
    [ -f "$path" ] || continue
    if house_demo_marked "$path"; then
      rm -f "$path"
      demo_slugs="$demo_slugs$slug "
      printf 'house: removed demo area %s\n' "$slug"
      removed=$((removed + 1))
    else
      printf 'house: kept %s (not a demo fixture)\n' "$slug"
    fi
  done

  # A prescription belongs to the fixture only when the chart it was written
  # for was one. A real chart at a demo slug must keep its real prescription, so
  # only a slug the fixture itself removed licenses deleting its outbox. Anything
  # else is left in place and named, never guessed away.
  for slug in $HOUSE_DEMO_SLUGS; do
    case "$demo_slugs" in
    *" $slug "*) ;;
    *)
      for f in "$HOUSE_OUTBOX/$slug"-*.md; do
        [ -e "$f" ] || continue
        printf 'house: kept prescription %s (area %s is not a demo fixture)\n' "${f##*/}" "$slug"
      done
      continue
      ;;
    esac
    for f in "$HOUSE_OUTBOX/$slug"-*.md; do
      [ -e "$f" ] || continue
      rm -f "$f"
      printf 'house: removed demo prescription %s\n' "${f##*/}"
    done
  done

  [ "$removed" -gt 0 ] || printf 'house: no demo areas to clear\n'
}

ACTION=${1:-}
[ $# -gt 0 ] && shift || true

case "$ACTION" in
-h | --help)
  usage
  exit 0
  ;;
seed) seed "$@" ;;
clear)
  [ $# -eq 0 ] || house_die "usage: house-demo.sh clear"
  clear
  ;;
*)
  house_die "usage: house-demo.sh seed [--bind <crew-id>] | clear (try --help)"
  ;;
esac
